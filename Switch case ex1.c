#include<stdio.h>
void main()
{
	int digit;
	
	printf("\n Enter digit:");
	scanf("%d",&digit);
	
	switch(digit)
	{
	    case 0:
		       printf("\n it is zero:");
	           break;
		
    	case 1:
	          printf("\n it is one:");
		      break;
			
	    case 2:
		      printf("\n it is two:");
		      break;
		
	    case 4:
		      printf("\n it is four:");
		      break;
		
	    case 5:
		      printf("\n it is five:");
		      break;
		
	    case 6:
		      printf("\n it is six:");
		      break;
		
	    case 7:
		     printf("\n it is seven:");
		     break;
		
	    case 8:
		      printf("\n it is eight:");
		      break;
		
	    case 9:
		      printf("\n it is night:");
		      break;
		
	    case 10:
		       printf("\n it is ten:");
		       break;
		
	    default:
		       printf("\n it is invalid digit:");	
    }
}
	
	
	
	
	
	
	
	
	
	
	
	
	
	
	
